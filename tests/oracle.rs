/// The third-party `jojodiff` crate (v0.1.2) applies the Rust-produced
/// patches of the NUL-free text pair. Its `patch` signature takes both
/// readers as the same concrete type (`patch<R: Read + Seek, W: Write>(
/// in_reader: &mut R, patch_reader: &mut R, out_writer: &mut W)`), so
/// `Cursor<Vec<u8>>` is used for both. Its reader defaults the operator to
/// MOD (the 0.8.5 reader semantics of spec §18.C), so the implicit-MOD
/// patches keep restoring the new files byte-exact.
#[test]
fn francisdb_cross_validation() {
    let (pair, org, new) = PAIRS[1]; // text pair, NUL-free (spec §16.4)
    let org_bytes = fs::read(fixture(org)).expect("read original file");
    let new_bytes = fs::read(fixture(new)).expect("read new file");
    for (name, opts, _) in patch_sets() {
        let dir = common::scratch(&format!("fdb-{pair}-{name}"));
        let patch = dir.path().join("patch.jdf");
        let d = run_in(
            dir.path(),
            Path::new(env!("CARGO_BIN_EXE_jdiff")),
            &jdiff_args(opts, &fixture(org), &fixture(new), &patch),
        );
        assert_exit1(&d, &format!("jdiff {pair}/{name}"));
        let patch_bytes = fs::read(&patch).expect("read patch");

        let mut org_reader = Cursor::new(org_bytes.clone());
        let mut patch_reader = Cursor::new(patch_bytes);
        let mut out: Vec<u8> = Vec::new();
        jojodiff::patch(&mut org_reader, &mut patch_reader, &mut out)
            .expect("francisdb jojodiff::patch");
        assert_eq!(
            out, new_bytes,
            "francisdb-applied patch differs for {pair}/{name}"
        );
        drop(dir);
    }
}
