//! Oracle conformance harness (spec §13 test corpus + §22 acceptance gates;
//! port plan Task 12, re-pointed to the 0.8.5 oracle in Task 20, golden85
//! layer regenerated in Task 22).
//!
//! Four layers (one numbering everywhere — README, CONTRIBUTING, here):
//!
//! 1. **Round-trip gate** (runs everywhere, spec §22.1): `jdiff OPTS A B p &&
//!    jdiff -u A p out` restores B byte-exact across the whole matrix, plus
//!    the francisdb cross-validation (§16.4: the third-party `jojodiff` crate
//!    applies the Rust-produced patches of the NUL-free text pair — its
//!    reader defaults the operator to MOD, the 0.8.5 reader semantics, so
//!    implicit-MOD patches apply).
//! 2. **Golden byte-compare** (runs everywhere): the Rust `jdiff` output
//!    must be byte-identical to the committed 0.8.5-oracle goldens under
//!    `tests/fixtures/golden85/<pair>/<optset>.*` — patches, `-l`/`-r`
//!    listings, and `-vv` stderr with the one run-dependent stats line
//!    masked. The goldens are generated by `scripts/gen-golden.sh` from the
//!    compiled C++ 0.8.5 reference (never from Rust output), captured at
//!    un-overridden oracle defaults (port and oracle build identical index
//!    tables since §21.18: 12 bytes/element on both sides). The 0.8.1
//!    goldens under `tests/fixtures/golden/` are never compared here — they
//!    re-pin the cross-version gate (tests/crossver.rs, layer 3, §22.3).
//! 3. **Cross-version gate** (runs everywhere): every committed 0.8.1 golden
//!    patch applies with `jdiff -u` and an argv[0]=`jptch` copy and restores
//!    byte-exact (tests/crossver.rs, §22.3).
//! 4. **Live-oracle byte-compare** (auto-skips): when the compiled C++ 0.8.5
//!    reference is present (`$JOJODIFF_ORACLE`, else `target/oracle/jdiff`
//!    from `scripts/build-oracle.sh`), the Rust and C++ binaries are compared
//!    directly: patch bytes and `-l`/`-r` listings across the §22.1 matrix on
//!    the tiny pair and the corpus pairs, verbose stderr with the one
//!    documented port deviation masked, and cross-applied patches
//!    (`jdiff -u` on both sides).
//!
//! The bundled corpus (`bkocomu.0000.fil`/`bkocomu.0009.fil`, ~1.8 MB binary
//! with NULs; `test2.001.txt`/`test2.002.txt`, CRLF text) is vendored
//! byte-exact from the C++ repo's `tests/` directory. Both pairs differ, so
//! every `jdiff` run below must exit 1 (differences found — 0.8.5 swapped the
//! exit codes); the identical-files exit-0 case is pinned in
//! `tests/roundtrip.rs`.

mod common;

use std::ffi::{OsStr, OsString};
use std::fs;
use std::io::Cursor;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use tempfile::TempDir;

/// The two bundled corpus pairs: (golden directory name, original, new).
const PAIRS: &[(&str, &str, &str)] = &[
    ("bkocomu", "bkocomu.0000.fil", "bkocomu.0009.fil"),
    ("test2", "test2.001.txt", "test2.002.txt"),
];

/// Option matrix of spec §22.1 (0.8.5 CLI), applied to both pairs:
/// (name, jdiff arguments, output-file extension). `-l`/`-r` produce listings
/// (`.asc`/`.rgn`), the rest produce binary patches (`.jdf`).
const OPTION_SETS: &[(&str, &[&str], &str)] = &[
    ("default", &[], "jdf"),
    ("b", &["-b"], "jdf"),
    ("bb", &["-bb"], "jdf"),
    ("f", &["-f"], "jdf"),
    ("ff", &["-ff"], "jdf"),
    ("p", &["-p"], "jdf"),
    ("q", &["-q"], "jdf"),
    ("pq", &["-p", "-q"], "jdf"),
    ("s", &["-s"], "jdf"),
    ("i1", &["-i", "1"], "jdf"),
    ("i8", &["-i", "8"], "jdf"),
    ("i512", &["-i", "512"], "jdf"),
    ("k0", &["-k", "0"], "jdf"),
    ("k1", &["-k", "1"], "jdf"),
    ("k65565", &["-k", "65565"], "jdf"),
    ("n1x2", &["-n", "1", "-x", "2"], "jdf"),
    ("x5", &["-x", "5"], "jdf"),
    ("m0", &["-m", "0"], "jdf"),
    ("m7", &["-m", "7"], "jdf"),
    ("m2048", &["-m", "2048"], "jdf"),
    ("a0", &["-a", "0"], "jdf"),
    ("a1", &["-a", "1"], "jdf"),
    ("l", &["-l"], "asc"),
    ("r", &["-r"], "rgn"),
];

/// Verbose stderr captures compared live against the oracle on the tiny pair.
const VERBOSE_LEVELS: &[(&str, &str)] = &[("v", "-v"), ("vv", "-vv")];

/// Tiny fixture pair (as in tests/roundtrip.rs) for the byte-exact live
/// comparisons: small enough that both engines land on identical match
/// decisions at every option set (port and oracle build identical index
/// tables, spec §21.18).
const TINY_ORG: &[u8] = b"hello world hello";
const TINY_NEW: &[u8] = b"hello world byebye";

/// The matrix entries that produce an appliable binary patch (no `-l`/`-r`).
fn patch_sets() -> Vec<(&'static str, &'static [&'static str], &'static str)> {
    OPTION_SETS
        .iter()
        .filter(|&(_, _, ext)| *ext == "jdf")
        .copied()
        .collect()
}

/// Option sets for the round-trip gate: every patch-producing set (the two
/// listing sets round-trip a default patch in tests/roundtrip.rs already).
fn roundtrip_sets(pair: &str) -> Vec<(&'static str, &'static [&'static str])> {
    let _ = pair;
    patch_sets().into_iter().map(|(n, o, _)| (n, o)).collect()
}

fn fixtures_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("fixtures")
}

fn golden85_dir() -> PathBuf {
    fixtures_dir().join("golden85")
}

fn fixture(file: &str) -> PathBuf {
    fixtures_dir().join(file)
}

/// Directory holding the compiled C++ 0.8.5 reference (`jdiff` — 0.8.5 ships
/// a single binary, spec §18.B), or None. Honours `$JOJODIFF_ORACLE`, else
/// falls back to `target/oracle` as created by `scripts/build-oracle.sh`.
fn oracle_dir() -> Option<PathBuf> {
    // Relative $JOJODIFF_ORACLE values must be made absolute: the tests spawn
    // the oracle binaries with `current_dir` set to a temp directory, which
    // would otherwise resolve the path against that directory.
    fn find(dir: &Path) -> Option<PathBuf> {
        if dir.join("jdiff").is_file() {
            dir.canonicalize().ok()
        } else {
            None
        }
    }
    if let Some(dir) = std::env::var_os("JOJODIFF_ORACLE") {
        return find(&PathBuf::from(dir));
    }
    find(
        &PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("target")
            .join("oracle"),
    )
}

/// Run a binary with OsString `args` inside `dir`.
fn run_in(dir: &Path, exe: &Path, args: &[OsString]) -> Output {
    Command::new(exe)
        .args(args)
        .current_dir(dir)
        .output()
        .unwrap_or_else(|e| panic!("spawn {}: {e}", exe.display()))
}

/// jdiff argument vector for an option set: `[opts…] org new out` (absolute
/// fixture paths, output file last) so Rust and C++ runs are comparable.
fn jdiff_args(opts: &[&str], org: &Path, new: &Path, out: &Path) -> Vec<OsString> {
    let mut args: Vec<OsString> = opts.iter().map(|o| OsStr::new(o).to_os_string()).collect();
    args.push(org.as_os_str().to_os_string());
    args.push(new.as_os_str().to_os_string());
    args.push(out.as_os_str().to_os_string());
    args
}

fn apply_args(org: &Path, patch: &Path, out: &Path) -> Vec<OsString> {
    let mut args: Vec<OsString> = vec![OsStr::new("-u").to_os_string()];
    args.push(org.as_os_str().to_os_string());
    args.push(patch.as_os_str().to_os_string());
    args.push(out.as_os_str().to_os_string());
    args
}

fn assert_exit0(out: &Output, what: &str) {
    assert!(
        out.status.success(),
        "{what} exited with code {:?}\nstderr:\n{}",
        out.status.code(),
        String::from_utf8_lossy(&out.stderr)
    );
}

/// Asserts a differing-pair jdiff run exited 1 (0.8.5 exit swap).
fn assert_exit1(out: &Output, what: &str) {
    assert_eq!(
        out.status.code(),
        Some(1),
        "{what} exited with code {:?}\nstderr:\n{}",
        out.status.code(),
        String::from_utf8_lossy(&out.stderr)
    );
}

