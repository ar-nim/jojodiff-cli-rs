/// The only masked line of the golden85 verbose gate. The C++ never
/// initializes the "Inaccurate  solutions" counter (spec §21.5/§21.6): the
/// oracle prints different garbage on every run while the port prints its
/// deterministic real count, so the line can never byte-match.
/// `scripts/gen-golden.sh` masks it before committing the capture; this mask
/// reduces the port's output to the same placeholder. Every other stats line
/// is deterministic and gates byte-exact.
fn mask_inaccurate_line(stderr: &str) -> String {
    let mut out = stderr
        .lines()
        .map(|line| {
            if line.starts_with("Inaccurate  solutions") {
                "Inaccurate  solutions   = (masked)"
            } else {
                line
            }
        })
        .collect::<Vec<_>>()
        .join("\n");
    if stderr.ends_with('\n') {
        out.push('\n');
    }
    out
}

/// The committed goldens under `tests/fixtures/golden85/` are captures of
/// the 0.8.5 oracle (`scripts/gen-golden.sh`): the Rust `jdiff` must
/// reproduce them byte-for-byte on every machine, across the §22.1 matrix
/// minus the pipe-only variants (patches and `-l`/`-r` listings; the `-vv`
/// streams are gated separately below). The captures run un-overridden
/// oracle defaults: port and oracle build identical index tables since the
/// §21.18 divisor ruling (12 bytes/element on both sides), so the committed
/// bytes pin exactly what the port must print for the set's own option
/// values. The one matrix cell without a committed golden (documented in
/// gen-golden.sh) is skipped here: the ~80 MB bkocomu/l.asc listing
/// (live-oracle coverage).
#[test]
fn golden85_jdiff_outputs_match() {
    assert!(
        golden85_dir().is_dir(),
        "committed goldens missing at {} - run scripts/gen-golden.sh (goldens are\n\
         generated by the C++ oracle, never from Rust output)",
        golden85_dir().display()
    );
    for (pair, org, new) in PAIRS {
        for (name, opts, ext) in OPTION_SETS {
            // The ~80 MB bkocomu/l.asc listing is live-oracle coverage only
            // (gen-golden.sh header).
            if *pair == "bkocomu" && *name == "l" {
                continue;
            }
            let golden = golden85_dir().join(pair).join(format!("{name}.{ext}"));
            let golden_bytes = fs::read(&golden)
                .unwrap_or_else(|e| panic!("read golden {}: {e}", golden.display()));
            let dir = common::scratch(&format!("g85-{pair}-{name}"));
            let out = dir.path().join("output.bin");
            let outp = run_in(
                dir.path(),
                Path::new(env!("CARGO_BIN_EXE_jdiff")),
                &jdiff_args(opts, &fixture(org), &fixture(new), &out),
            );
            assert_exit1(&outp, &format!("rust jdiff {pair}/{name}"));
            assert!(
                outp.stdout.is_empty(),
                "rust jdiff {pair}/{name}: stdout must stay empty (output goes to the file)"
            );
            let rust_bytes = fs::read(&out).expect("rust jdiff output");
            assert_eq!(
                rust_bytes, golden_bytes,
                "rust jdiff output diverges from 0.8.5-oracle golden for {pair}/{name}"
            );
            drop(dir);
        }
    }
}

/// Rust `jdiff -vv` stderr must equal the committed golden85 captures of the
/// 0.8.5 oracle (patch sets of both pairs: greeting, echo, progress and the
/// statistics blocks) with one documented exception: the run-dependent
/// "Inaccurate  solutions" line is masked on both sides (see
/// [`mask_inaccurate_line`]).
#[test]
fn golden85_verbose_stderr_matches() {
    for (pair, org, new) in PAIRS {
        for (name, opts) in patch_sets().into_iter().map(|(n, o, _)| (n, o)) {
            let golden = golden85_dir().join(pair).join(format!("{name}.vv.stderr"));
            let golden_bytes = fs::read(&golden)
                .unwrap_or_else(|e| panic!("read golden {}: {e}", golden.display()));
            let dir = common::scratch(&format!("g85v-{pair}-{name}"));
            let out = dir.path().join("output.bin");
            let mut all: Vec<&str> = vec!["-vv"];
            all.extend_from_slice(opts);
            let outp = run_in(
                dir.path(),
                Path::new(env!("CARGO_BIN_EXE_jdiff")),
                &jdiff_args(&all, &fixture(org), &fixture(new), &out),
            );
            assert_exit1(&outp, &format!("rust jdiff -vv {pair}/{name}"));
            assert!(
                outp.stdout.is_empty(),
                "verbose output goes to stderr by default ({pair}/{name} -vv)"
            );
            assert_eq!(
                mask_inaccurate_line(&String::from_utf8_lossy(&outp.stderr)),
                String::from_utf8_lossy(&golden_bytes).into_owned(),
                "rust jdiff verbose stderr diverges from 0.8.5-oracle golden for {pair}/{name}"
            );
            drop(dir);
        }
    }
}

// ---------------------------------------------------------------------------
// Layer 4: live-oracle byte-compare (auto-skips without the 0.8.5 oracle)
// ---------------------------------------------------------------------------

fn skip_message() -> &'static str {
    "skipping: no 0.8.5 oracle ($JOJODIFF_ORACLE unset and target/oracle/jdiff missing)"
}

/// Mask for the one documented port-vs-oracle deviation in the verbose
/// stream (spec §21.5/§21.6), applied to both sides before comparing: the
/// "Inaccurate  solutions" line prints the C++ uninitialized counter
/// baseline on the oracle and the port's deterministic 0. (The "Index table
/// size" line needs no mask: both sides print the same prime since §21.18.)
fn mask_deviation_lines(stderr: &str) -> String {
    stderr
        .lines()
        .map(|line| {
            if line.starts_with("Inaccurate  solutions") {
                "Inaccurate  solutions   (masked)"
            } else {
                line
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

/// Direct Rust-vs-C++ 0.8.5 comparison across the §22.1 matrix:
/// - tiny pair: patch/listing bytes and exit codes byte-exact on every set;
/// - corpus pairs: patch and listing bytes byte-exact on every set (port and
///   oracle build identical index tables, spec §21.18 — including the ~80 MB
///   bkocomu `-l` listing that is not a committed golden); appliable patches
///   additionally round-trip through each binary's own `-u`.
#[test]
fn live_oracle_jdiff_matches() {
    let Some(oracle) = oracle_dir() else {
        eprintln!("{}", skip_message());
        return;
    };
    let oracle_jdiff = oracle.join("jdiff");
    let rust_jdiff = PathBuf::from(env!("CARGO_BIN_EXE_jdiff"));

    // Tiny pair: write fixtures, byte-compare every set's output.
    let tdir = common::scratch("live-tiny");
    let org = tdir.path().join("a.bin");
    let new = tdir.path().join("b.bin");
    fs::write(&org, TINY_ORG).unwrap();
    fs::write(&new, TINY_NEW).unwrap();
    for (name, opts, _) in OPTION_SETS {
        let mut outs: Vec<(TempDir, Output, PathBuf)> = Vec::new(); // (dir, output, out-file)
        for (tag, exe) in [("cpp", &oracle_jdiff), ("rs", &rust_jdiff)] {
            let dir = common::scratch(&format!("live-tiny-{name}-{tag}"));
            let out_file = dir.path().join("output.bin");
            let outp = run_in(dir.path(), exe, &jdiff_args(opts, &org, &new, &out_file));
            assert_exit1(&outp, &format!("{tag} jdiff tiny/{name}"));
            assert!(
                outp.stdout.is_empty(),
                "{tag} jdiff tiny/{name}: stdout must stay empty"
            );
            outs.push((dir, outp, out_file));
        }
        let (dir_cpp, outp_cpp, file_cpp) = outs.remove(0);
        let (dir_rs, outp_rs, file_rs) = outs.remove(0);
        assert_eq!(
            fs::read(&file_rs).expect("rs output"),
            fs::read(&file_cpp).expect("cpp output"),
            "Rust and C++ jdiff diverge for tiny/{name}"
        );
        assert_eq!(outp_rs.status.code(), outp_cpp.status.code());
        drop(dir_cpp);
        drop(dir_rs);
    }
    drop(tdir);

    // Corpus pairs: byte-compare every set's output (patch sets AND the
    // `-l`/`-r` listings, including the ~80 MB bkocomu `-l` that is not a
    // committed golden); appliable patches additionally round-trip through
    // each binary's own `-u` (listings are diagnostics no patcher applies,
    // spec §21.16).
    for (pair, org, new) in PAIRS {
        let new_bytes = fs::read(fixture(new)).expect("read new file");
        for (name, opts, ext) in OPTION_SETS {
            let mut outs: Vec<(TempDir, Output, PathBuf)> = Vec::new();
            for (tag, exe) in [("cpp", &oracle_jdiff), ("rs", &rust_jdiff)] {
                let dir = common::scratch(&format!("live-{pair}-{name}-{tag}"));
                let output = dir.path().join("output.bin");
                let outp = run_in(
                    dir.path(),
                    exe,
                    &jdiff_args(opts, &fixture(org), &fixture(new), &output),
                );
                assert_exit1(&outp, &format!("{tag} jdiff {pair}/{name}"));
                outs.push((dir, outp, output));
            }
            let (dir_cpp, _, file_cpp) = outs.remove(0);
            let (dir_rs, _, file_rs) = outs.remove(0);
            assert_eq!(
                fs::read(&file_rs).expect("rs output"),
                fs::read(&file_cpp).expect("cpp output"),
                "Rust and C++ jdiff diverge for {pair}/{name}"
            );
            if *ext != "jdf" {
                drop(dir_cpp);
                drop(dir_rs);
                continue;
            }
            for (dir, exe, patch) in [
                (dir_rs, &rust_jdiff, file_rs),
                (dir_cpp, &oracle_jdiff, file_cpp),
            ] {
                let restored = dir.path().join("restored.bin");
                let outp = run_in(
                    dir.path(),
                    exe,
                    &apply_args(&fixture(org), &patch, &restored),
                );
                assert_exit0(&outp, &format!("{} -u {pair}/{name}", exe.display()));
                assert_eq!(
                    fs::read(&restored).expect("restored"),
                    new_bytes,
                    "round-trip failed for {pair}/{name}"
                );
                drop(dir);
            }
        }
    }
}

/// Live Rust-vs-C++ comparison of `jdiff` verbose stderr on the tiny pair,
/// byte-exact after masking the one documented deviation (the
/// inaccurate-solutions baseline; the index-table lines match since §21.18).
#[test]
fn live_oracle_verbose_stderr_matches() {
    let Some(oracle) = oracle_dir() else {
        eprintln!("{}", skip_message());
        return;
    };
    let tdir = common::scratch("lverb-tiny");
    let org = tdir.path().join("a.bin");
    let new = tdir.path().join("b.bin");
    fs::write(&org, TINY_ORG).unwrap();
    fs::write(&new, TINY_NEW).unwrap();
    for (vtag, vopt) in VERBOSE_LEVELS {
        let mut runs: Vec<(TempDir, Output)> = Vec::new();
        for (tag, exe) in [
            ("cpp", oracle.join("jdiff")),
            ("rs", PathBuf::from(env!("CARGO_BIN_EXE_jdiff"))),
        ] {
            let dir = common::scratch(&format!("lverb-tiny-{vtag}-{tag}"));
            let out_file = dir.path().join("output.bin");
            let outp = run_in(
                dir.path(),
                &exe,
                &jdiff_args(&[vopt], &org, &new, &out_file),
            );
            assert_exit1(&outp, &format!("{tag} jdiff -{vtag} tiny"));
            runs.push((dir, outp));
        }
        let (dir_cpp, outp_cpp) = runs.remove(0);
        let (dir_rs, outp_rs) = runs.remove(0);
        assert_eq!(
            mask_deviation_lines(&String::from_utf8_lossy(&outp_rs.stderr)),
            mask_deviation_lines(&String::from_utf8_lossy(&outp_cpp.stderr)),
            "Rust and C++ jdiff verbose stderr diverge for tiny -{vtag}"
        );
        drop(dir_cpp);
        drop(dir_rs);
    }
    drop(tdir);
}

/// Cross-applies patches through both binaries' `-u`: for the tiny pair,
/// every patch-producing matrix set must restore the new file when applied
/// by EITHER binary (0.8.5 reader ⇄ 0.8.5 writer, spec §18.C).
#[test]
fn live_oracle_patch_cross_applies() {
    let Some(oracle) = oracle_dir() else {
        eprintln!("{}", skip_message());
        return;
    };
    let oracle_jdiff = oracle.join("jdiff");
    let rust_jdiff = PathBuf::from(env!("CARGO_BIN_EXE_jdiff"));
    let tdir = common::scratch("cross-tiny");
    let org = tdir.path().join("a.bin");
    let new = tdir.path().join("b.bin");
    fs::write(&org, TINY_ORG).unwrap();
    fs::write(&new, TINY_NEW).unwrap();

    for (name, opts, ext) in OPTION_SETS {
        if *ext != "jdf" {
            continue;
        }
        // The maker scratch dirs must outlive their patches: the RAII
        // TempDir would delete patch.jdf at the inner scope's end, so the
        // dirs are kept (and dropped) alongside the patch paths. (The old
        // manual helper leaked these dirs until process end; the TempDir
        // now cleans them up deterministically after the apply loop.)
        let mut patches: Vec<(&str, TempDir, PathBuf)> = Vec::new();
        for (tag, exe) in [("cpp", &oracle_jdiff), ("rs", &rust_jdiff)] {
            let dir = common::scratch(&format!("cross-tiny-{name}-{tag}"));
            let patch = dir.path().join("patch.jdf");
            let outp = run_in(dir.path(), exe, &jdiff_args(opts, &org, &new, &patch));
            assert_exit1(&outp, &format!("{tag} jdiff tiny/{name}"));
            patches.push((tag, dir, patch));
        }
        for (maker, _maker_dir, patch) in &patches {
            for (tag, exe) in [("cpp", &oracle_jdiff), ("rs", &rust_jdiff)] {
                let dir = common::scratch(&format!("cross-tiny-{name}-{maker}-by-{tag}"));
                let restored = dir.path().join("restored.bin");
                let outp = run_in(dir.path(), exe, &apply_args(&org, patch, &restored));
                assert_exit0(&outp, &format!("{tag} -u of {maker} patch tiny/{name}"));
                assert_eq!(
                    fs::read(&restored).expect("restored"),
                    TINY_NEW,
                    "{maker} patch applied by {tag} diverges for tiny/{name}"
                );
                drop(dir);
            }
        }
    }
    drop(tdir);
}

